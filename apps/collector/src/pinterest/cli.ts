import {parseArgs} from 'node:util';
import {mkdir,writeFile,chmod} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
import {collectPinterest} from './adapter';
const {values}=parseArgs({options:{keyword:{type:'string'},country:{type:'string'},limit:{type:'string',default:'3'},out:{type:'string'},channel:{type:'string',default:'chrome'}}});
if(!values.keyword||!values.country||!values.out)throw Error('Usage: cli.ts --keyword Nike --country DE --limit 3 --out <private-directory> [--channel chrome|chromium]');
if(!['chrome','chromium'].includes(values.channel!))throw Error('BROWSER_CHANNEL_INVALID');
const out=resolve(values.out);await mkdir(out,{recursive:true,mode:0o700});await chmod(out,0o700);
const result=await collectPinterest({keyword:values.keyword,country:values.country,limit:Number(values.limit),channel:values.channel as 'chrome'|'chromium'});
const raw=JSON.stringify(result,null,2);const sha=createHash('sha256').update(raw).digest('hex');
const file=join(out,`pinterest-${sha}.json`);await writeFile(file,raw,{mode:0o600,flag:'wx'});
console.log(JSON.stringify({status:result.status,errorCode:result.errorCode,count:result.ads.length,source:result.sourceKey,platform:result.platform,evidenceFile:file,evidenceSha256:sha,coverage:result.coverage}));
if(!['SUCCEEDED','NO_RESULTS'].includes(result.status))process.exitCode=2;
