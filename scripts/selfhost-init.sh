#!/usr/bin/env bash
# Writes .env for docker-compose.yaml with fresh random secrets.
# Usage: scripts/selfhost-init.sh DOMAIN ADMIN_EMAIL
#   DOMAIN serves the web app; api.DOMAIN and s3.DOMAIN must point to the same host.
set -euo pipefail
repo_dir=$(cd "$(dirname "$0")/.." && pwd)
env_file="$repo_dir/.env"
domain=${1:-}
admin_email=${2:-}
if [[ -z $domain || -z $admin_email ]]; then
  echo "Usage: $0 DOMAIN ADMIN_EMAIL   (for a local trial: $0 localhost you@example.com)" >&2
  exit 1
fi
[[ -e $env_file ]] && { echo "$env_file already exists; edit it or move it away first." >&2; exit 1; }
command -v openssl >/dev/null || { echo "openssl is required." >&2; exit 1; }
hex() { openssl rand -hex "$1"; }

caddy_options=''
smtp='SMTP_HOST=
SMTP_PORT=587
SMTP_SECURE=false
SMTP_USERNAME=
SMTP_PASSWORD=
EMAIL_FROM='
if [[ $domain == localhost || $domain == *.localhost ]]; then
  # Local trial: Caddy's own CA and the bundled Mailpit inbox.
  caddy_options=local_certs
  smtp='SMTP_HOST=mailpit
SMTP_PORT=1025
SMTP_SECURE=false
SMTP_USERNAME=local
SMTP_PASSWORD=local
EMAIL_FROM=adtrender@mail.localhost'
fi

umask 077
cat > "$env_file" <<ENV
# Generated by scripts/selfhost-init.sh. Keep this file private.
APP_HOST=$domain
API_HOST=api.$domain
S3_HOST=s3.$domain
CADDY_GLOBAL_OPTIONS=$caddy_options

# Only these addresses may sign up while REGISTRATION_MODE=invite.
REGISTRATION_MODE=invite
REGISTRATION_ALLOWLIST=$admin_email

POSTGRES_PASSWORD=$(hex 24)
JWT_SECRET=$(hex 32)
OUTBOX_ENCRYPTION_KEY=$(hex 32)
RATE_LIMIT_HMAC_SECRET=$(hex 32)
GARAGE_RPC_SECRET=$(hex 32)
GARAGE_ACCESS_KEY=GK$(hex 12)
GARAGE_SECRET_KEY=$(hex 32)

# Verification and invitation emails need a real SMTP account in production.
$smtp

# Optional: AI analysis and Google sign-in.
OPENAI_API_KEY=
ANALYSIS_MODEL=
GOOGLE_AUTH_ENABLED=false
GOOGLE_CLIENT_ID=
GOOGLE_CLIENT_SECRET=
ENV
echo "Wrote $env_file."
if [[ -n $caddy_options ]]; then
  echo "Next: docker compose --profile mailpit up -d --build"
else
  echo "Fill in the SMTP_* values and EMAIL_FROM, point $domain, api.$domain and s3.$domain at this host, then: docker compose up -d --build"
fi
